// 称号（合計の星の数で決まる）
const RANKS = [
  { min: 0, name: "文法見習い", icon: "🌱" },
  { min: 10, name: "文法挑戦者", icon: "🔥" },
  { min: 25, name: "文法の達人", icon: "⚡" },
  { min: 45, name: "文法名人", icon: "🌟" },
  { min: 70, name: "文法王", icon: "👑" },
  { min: 95, name: "文法最強王", icon: "🏆" }
];
function rankFor(stars) {
  let r = RANKS[0];
  for (const x of RANKS) if (stars >= x.min) r = x;
  return r;
}
