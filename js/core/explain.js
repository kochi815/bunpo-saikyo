// explain.js ― 「なぜその品詞なのか」「なぜちがうのか」の説明文を組み立てる

const JOSHI_FUNC = {
  "が": "主語を表す", "を": "動作の相手（何を）を表す", "に": "場所・時・行き先を表す", "へ": "方向を表す",
  "と": "相手や、ならべるものを表す", "で": "場所や手段を表す", "から": "出発点を表す", "まで": "終点を表す",
  "の": "持ち主や説明を表す", "は": "主語（話題）を表す", "も": "同じものをならべる", "よ": "文の終わりで気持ちをそえる",
  "ね": "文の終わりで同意を求める", "か": "質問を表す", "て": "動作をつなぐ", "ので": "理由を表す", "ば": "条件を表す",
  "けれど": "反対の内容をつなぐ", "ながら": "同時にすることを表す", "だけ": "限る意味をそえる", "しか": "限る意味をそえる"
};

const AUX_INFO = {
  "ない": { m: "打ち消し", alt: "ない→なかった" }, "た": { m: "過去", alt: "た→たら" }, "たい": { m: "希望", alt: "たい→たかった" },
  "ます": { m: "丁寧", alt: "ます→ました" }, "です": { m: "丁寧", alt: "です→でした" }, "だ": { m: "断定", alt: "だ→だった" },
  "れる": { m: "受け身・可能など", alt: "れる→れた" }, "られる": { m: "受け身・可能など", alt: "られる→られた" },
  "せる": { m: "使役", alt: "せる→せた" }, "させる": { m: "使役", alt: "させる→させた" },
  "う": { m: "意志・さそい", alt: "" }, "よう": { m: "意志・さそい", alt: "" },
  "らしい": { m: "推定", alt: "らしい→らしかった" }, "そうだ": { m: "様子", alt: "そうだ→そうだった" }, "ようだ": { m: "たとえ・推定", alt: "ようだ→ようだった" }
};

const NOUN_KIND = { "もの": "もの", "人": "人", "こと": "ことがら", "場所": "場所", "時": "時", "数": "数", "代": "人やものを指す言葉（代名詞）" };

const Explain = {
  // その言葉が、その品詞である理由（正解時・ヒント3段目に使う）
  reasonOf(t) {
    if (t.why) return t.why;
    const w = t.w, pos = t.pos, base = t.base || t.w;
    switch (pos) {
      case "名詞": {
        const kind = NOUN_KIND[t.k] || "人・もの・こと";
        if (t.from) return `「${w}」は「${t.ex}」のように「〜が」「〜を」をつけられるので名詞。もとは${t.fromPos}「${t.from}」だけど、形が変わって名前を表す言葉になっているよ。`;
        if (t.k === "代") return `「${w}」は${kind}で、名詞の仲間。「${w}が」「${w}は」と主語になれるね。`;
        if (t.k === "数") return `「${w}」は数を表す名詞（数詞）。「${w}が」「${w}を」と言えるね。`;
        return `「${w}」は${kind}の名前を表す言葉。「${w}が」「${w}を」と言えるので名詞。`;
      }
      case "動詞": {
        const last = base.slice(-1);
        const back = w !== base ? `言い切りの形にもどすと「${base}」。` : "";
        const att = t.att ? `（後ろの「${t.att}」はくっついた別の言葉）` : "";
        return `「${w}」は動きや存在を表す言葉。${back}最後の「${last}」はウ段の音なので動詞。${att}`;
      }
      case "形容詞": {
        const back = w !== base ? `言い切りの形にもどすと「${base}」。` : "";
        const att = t.att ? `（後ろの「${t.att}」はくっついた別の言葉）` : "";
        const ex = t.n ? `「${base}${t.n}」と言えるね。` : "";
        return `「${w}」は様子を表す言葉。${back}「い」で終わるので形容詞。${ex}${att}`;
      }
      case "形容動詞": {
        const stem = base.slice(0, -1);
        const back = w !== base ? `言い切りの形にもどすと「${base}」。` : "";
        const ex = t.n ? `「${stem}な${t.n}」` : `「${stem}な＋名詞」`;
        return `「${w}」は様子を表す言葉。${back}「だ」で終わり、${ex}と言えるので形容動詞。`;
      }
      case "副詞":
        return `「${w}」は形が変わらず、${t.ex ? `「${t.ex}」のように` : ""}動詞や形容詞などをくわしくする言葉なので副詞。`;
      case "連体詞":
        return `「${w}」は形が変わらず、${t.ex ? `「${t.ex}」のように` : ""}必ず後ろの名詞をくわしくする言葉なので連体詞。`;
      case "接続詞": {
        const c = t.cat && CONJ_CATS[t.cat] ? `（${t.cat}：${CONJ_CATS[t.cat].desc}）` : "";
        return `「${w}」は前の文と後ろの文をつなぐ言葉なので接続詞${c}。`;
      }
      case "感動詞":
        return `「${w}」は${t.k || "感動や呼びかけなど"}を表す言葉で、「${w}。」だけで文になるので感動詞。`;
      case "助詞": {
        const f = t.func || JOSHI_FUNC[w] || "言葉と言葉の関係を表す";
        return `「${w}」は他の言葉の後ろにくっついて${f}言葉。形が変わらないので助詞。`;
      }
      case "助動詞": {
        const info = AUX_INFO[base] || AUX_INFO[w] || {};
        const m = t.m || info.m;
        const alt = t.alt != null ? t.alt : info.alt;
        const back = w !== base ? `（「${w}」は「${base}」が形を変えたもの）` : "";
        return `「${w}」は他の言葉の後ろにくっついて${m ? m + "の意味を足す" : "意味を足す"}言葉${back}。${alt ? `形が変わる（${alt}）ので` : ""}助動詞。`;
      }
    }
    return `「${w}」は${pos}。`;
  },

  // その言葉が「chosen」ではない理由（まちがえたときに使う）
  notReason(t, chosen) {
    if (t.not && t.not[chosen]) return t.not[chosen];
    const w = t.w, pos = t.pos, base = t.base || t.w;
    const stem = (pos === "形容詞" || pos === "形容動詞") ? base.slice(0, -1) : base;
    const ii = w !== base ? `言い切り「${base}」が` : "";  // 形が変わっているときだけ言い切りを示す
    const key = pos + ">" + chosen;
    const P = POS[chosen];
    const generic = P ? `「${w}」は${chosen}ではないよ。${chosen}は${P.short}（例：${P.ex.slice(0, 2).join("・")}）。` : `「${w}」は${chosen}ではないよ。`;
    switch (key) {
      // ---- 動詞が正解 ----
      case "動詞>名詞": return `「${w}」は動きを表していて、「${base}が」「${base}を」とは言えないね。名詞は「犬」「学校」のような名前の言葉。`;
      case "動詞>形容詞": return `「${w}」は${ii}「い」で終わらないね。形容詞は「楽しい」のように「い」で終わる。`;
      case "動詞>形容動詞": return `「${w}」は「だ」で言い切らないし、「〜な＋名詞」にもならないね。形容動詞は「静かだ・静かな」のような言葉。`;
      case "動詞>副詞": return `「${w}」は動きを表し、形が変わる言葉。副詞は「とても」のように形が変わらず、動詞などをくわしくする言葉だよ。`;
      case "動詞>連体詞": return `「${w}」は動きを表し、形が変わる。連体詞は「この」「大きな」のように形が変わらず、名詞の前にだけ来る言葉だよ。`;
      // ---- 名詞が正解 ----
      case "名詞>動詞": return `「${w}」は動きではなく名前を表す言葉。「${w}が」「${w}を」と言えるね。動詞なら「走る」のようにウ段で終わるよ。`;
      case "名詞>形容詞": return `「${w}」は「い」で終わる様子の言葉ではないね。「${w}が」と主語にできるので名詞。`;
      case "名詞>形容動詞": return `「${w}」は「だ」で終わる様子の言葉ではなく、名前を表す言葉。「${w}が」「${w}を」と言えるよ。`;
      case "名詞>副詞": return `「${w}」は「${w}が」「${w}を」と言えるね。副詞はそう言えない（「とてもが」×）。`;
      case "名詞>連体詞": return `連体詞は「この本」のように後ろに必ず名詞が来る言葉。「${w}」はそれ自体が名詞で、「${w}が」と言えるよ。`;
      case "名詞>感動詞": return `「${w}」は名前を表す言葉で、「${w}が」「${w}を」と言える。感動詞は「はい」「ああ」のように、それだけで文になる言葉だよ。`;
      // ---- 形容詞が正解 ----
      case "形容詞>動詞": return `「${w}」は動きではなく様子を表す言葉。${ii}「い」で終わるね。動詞はウ段で終わるよ。`;
      case "形容詞>名詞": return `「${w}」は「${base}が」「${base}を」と言えないね。様子を表して「い」で終わるので形容詞。`;
      case "形容詞>形容動詞": return `「${w}」は${ii}「い」で終わる。「だ」で終わらない（「${stem}だ」とは言わない）ので形容動詞ではないよ。`;
      case "形容詞>副詞": return `「${w}」は形が変わる言葉（${base}→${stem}く→${stem}かった）。形が変わらない副詞ではないよ。言い切りにもどせるなら副詞ではない。`;
      case "形容詞>連体詞": return `「${w}」は${ii}「い」で終わり、形が変わる（${stem}かった）。連体詞は「この」「大きな」のように形が変わらないよ。`;
      // ---- 形容動詞が正解 ----
      case "形容動詞>形容詞":
        if (w.endsWith("い")) return `「${w}」は「い」で終わって見えるけど、「${stem}な＋名詞」（${stem}な${t.n || "もの"}）と言えるので形容動詞。形容詞なら「${stem}い${t.n || "もの"}」になるはずだね。`;
        return `「${w}」は「い」ではなく「だ」で終わる${w !== base ? `（言い切り「${base}」）` : ""}。「${stem}な＋名詞」と言えるので形容動詞。`;
      case "形容動詞>動詞": return `「${w}」は動きではなく様子を表す言葉。${ii}「だ」で終わるね。動詞はウ段で終わるよ。`;
      case "形容動詞>名詞": return `「${w}」は「だ」で言い切り、「${stem}な＋名詞」と言えるので形容動詞。名詞なら「${stem}が」「${stem}を」の形で使うよ。`;
      case "形容動詞>副詞": return `「${w}」は形容動詞「${base}」が形を変えたもの（${base}→${stem}に→${stem}な）。形が変わる言葉は副詞ではないよ。`;
      case "形容動詞>連体詞": return `「${w}」は形容動詞「${base}」が形を変えたもの（${base}→${stem}な→${stem}に）。連体詞は形が変わらないよ。`;
      // ---- 副詞が正解 ----
      case "副詞>形容詞": return `「${w}」は「い」で終わらず、形も変わらない。形容詞は「大きい」のように「い」で終わり、形が変わる言葉だよ。`;
      case "副詞>形容動詞": return `「${w}」は「${w}だ」「${w}な」の形にならないね。形容動詞は「静かだ・静かな」となる言葉だよ。`;
      case "副詞>動詞": return `「${w}」は動きを表さず、言い切りの形もない（形が変わらない）。動詞はウ段で終わり、形が変わるよ。`;
      case "副詞>名詞": return `「${w}」は「${w}が」「${w}を」と言えないね。名詞は主語になれる名前の言葉だよ。`;
      case "副詞>連体詞": return `「${w}」の後ろに来るのは動詞や形容詞など${t.ex ? `（${t.ex}）` : ""}。名詞だけをかざる連体詞ではないよ。`;
      case "副詞>接続詞": return `「${w}」は文と文をつなぐのではなく、後ろの言葉をくわしくしている${t.ex ? `（${t.ex}）` : ""}。`;
      case "副詞>感動詞": return `「${w}」だけでは文にならない（「${w}。」×）。後ろの言葉をくわしくする言葉だよ。`;
      // ---- 連体詞が正解 ----
      case "連体詞>副詞": return `「${w}」の後ろには必ず名詞が来る${t.ex ? `（${t.ex}）` : ""}。動詞や形容詞をかざる副詞ではないよ。`;
      case "連体詞>形容詞": return `「${w}」は「い」で終わらず、形も変わらない（「${w}かった」×）。形容詞は「〜い」で終わり形が変わるよ。`;
      case "連体詞>形容動詞": return `「${w}」は「〜だ」で言い切る形がない。形容動詞なら「静かだ」のように「〜だ」と言えるよ。`;
      case "連体詞>名詞": return `「${w}」は「${w}が」「${w}を」と言えないね。必ず後ろに名詞が来る${t.ex ? `（${t.ex}）` : ""}ので連体詞。`;
      case "連体詞>動詞": return `「${w}」は動きを表さず、形も変わらない。動詞は「走る・走った」のように形が変わるよ。`;
      case "連体詞>接続詞": return `「${w}」は文と文をつながず、後ろの名詞をかざっている${t.ex ? `（${t.ex}）` : ""}。`;
      // ---- 接続詞が正解 ----
      case "接続詞>副詞": return `「${w}」は後ろの言葉をくわしくするのではなく、前の文と後ろの文をつないでいるね。`;
      case "接続詞>感動詞": return `「${w}」は一語で文にならず、前後をつなぐ働きをしている。感動詞は「はい」「ああ」のように一語で文になるよ。`;
      case "接続詞>連体詞": return `「${w}」は名詞をかざるのではなく、文と文をつないでいるね。`;
      // ---- 感動詞が正解 ----
      case "感動詞>接続詞": return `「${w}」は前後をつながない。「${w}。」だけで文になる${t.k || ""}の言葉だよ。`;
      case "感動詞>副詞": return `「${w}」は後ろの言葉をくわしくしない。「${w}。」だけで文になる言葉だよ。`;
      case "感動詞>名詞": return `「${w}」は名前ではなく${t.k || "感動や呼びかけ"}を表し、「${w}。」だけで文になるよ。`;
      case "感動詞>動詞": return `「${w}」は動きを表さず、形も変わらない。「${w}。」だけで文になる言葉だよ。`;
      // ---- 付属語 ----
      case "助詞>助動詞": return `「${w}」は形が変わらないね（「${w}」のまま）。形が変わらず関係を表すのは助詞。助動詞は「ない→なかった」のように形が変わるよ。`;
      case "助動詞>助詞": {
        if (t.notWhy) return t.notWhy;
        const info = AUX_INFO[base] || AUX_INFO[w] || {};
        const alt = t.alt != null ? t.alt : info.alt;
        return `「${w}」は${alt ? `形が変わる（${alt}）` : "意味を足す言葉"}。形が変わって意味を足すのは助動詞。助詞は形が変わらないよ。`;
      }
    }
    return generic;
  },

  // 主語・述語・修飾語の理由
  roleReason(sent, idx, role) {
    const ch = sent.chunks[idx];
    const text = ch.text;
    if (role === "述語") {
      const head = ch.head;
      let kind = "どうする";
      if (head.pos === "形容詞" || head.pos === "形容動詞") kind = "どんなだ";
      else if (head.pos === "名詞") kind = "何だ";
      else if (head.pos === "動詞" && (head.base === "ある" || head.base === "いる" || head.w === "ある" || head.w === "いる")) kind = "ある・いる";
      return `「${text}」は「${kind}」にあたり、文の最後にあるので述語。`;
    }
    if (role === "主語") {
      const pred = sent.chunks.find(c => c.role === "述語");
      return `述語「${pred ? pred.text : ""}」に「何が？」「だれが？」と聞くと「${text}」。だから主語。`;
    }
    if (role === "修飾語") {
      const tIdx = sent.mod[idx];
      const target = tIdx != null ? sent.chunks[tIdx] : null;
      const qw = Explain.modQuestion(ch, target);
      return `「${text}」は「${target ? target.text : ""}」を${qw ? `「${qw}」と` : ""}くわしくしているので修飾語。`;
    }
    if (role === "接続語") return `「${text}」は前の文と後ろの文をつないでいるので接続語。`;
    if (role === "独立語") return `「${text}」はほかの言葉と結びつかず、それだけで独立しているので独立語。`;
    return `「${text}」は${role}。`;
  },

  // 修飾語が答えている問い（どんな・どのように・何を…）
  modQuestion(ch, target) {
    if (!target) return "";
    const head = ch.head;
    if (target.head.pos === "名詞") return "どんな";
    if (head.pos === "名詞") {
      const p = ch.tokens.length > 1 ? ch.tokens[ch.tokens.length - 1].w : "";
      const byP = { "を": "何を", "で": "どこで・何で", "に": "どこに・いつ", "へ": "どこへ", "と": "だれと", "から": "どこから", "まで": "どこまで" }[p];
      if (byP) return byP;
      if (/[日朝夜晩昨今明毎時春夏秋冬]/.test(head.w)) return "いつ";
      if (/[一二三四五六七八九十百千]/.test(head.w)) return "どのくらい";
      return "いつ・どのくらい";
    }
    if (head.pos === "副詞") return "どのように・どのくらい";
    if (head.pos === "形容詞" || head.pos === "形容動詞") return "どのように";
    return "";
  },

  // 文節の中の単語の説明（タップ問題で、ちがう文節をタップしたとき）
  chunkPosNote(ch) {
    const h = ch.head;
    const back = h.base && h.base !== h.w ? `（言い切りの形は「${h.base}」）` : "";
    const rest = ch.tokens.slice(1);
    const tail = rest.length ? `。後ろの「${rest.map(t => t.w).join("")}」は${rest.map(t => t.pos).filter((v, i, a) => a.indexOf(v) === i).join("・")}` : "";
    if (ch.tokens.length === 1) return `「${ch.text}」は${h.pos}${back}`;
    return `「${ch.text}」の「${h.w}」は${h.pos}${back}${tail}`;
  }
};
